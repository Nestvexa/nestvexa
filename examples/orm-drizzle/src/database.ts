import { Inject, Injectable, Module } from '@nestjs/common';
import type { DynamicModule, OnModuleDestroy } from '@nestjs/common';
import { createClient } from '@libsql/client';
import type { Client } from '@libsql/client';
import { count, desc } from 'drizzle-orm';
import { drizzle } from 'drizzle-orm/libsql';
import type { LibSQLDatabase } from 'drizzle-orm/libsql';
import { migrate } from 'drizzle-orm/libsql/migrator';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { NOTES_STORE } from './notes.js';
import type { Note, NotesStore } from './notes.js';
import { notes } from './schema.js';
import * as schema from './schema.js';

/*
 * Drizzle ORM over libSQL (SQLite with prebuilt binaries and no install
 * scripts). Migrations are SQL files generated by drizzle-kit from
 * src/schema.ts (`pnpm --filter @nestvexa/example-orm-drizzle db:generate`)
 * and applied at startup by Drizzle's migrator.
 */

const CONNECTION = Symbol('CONNECTION');
const migrationsFolder = fileURLToPath(new URL('../drizzle', import.meta.url));

interface Connection {
  readonly client: Client;
  readonly db: LibSQLDatabase<typeof schema>;
}

@Injectable()
export class DrizzleNotesStore implements NotesStore, OnModuleDestroy {
  constructor(@Inject(CONNECTION) private readonly connection: Connection) {}
  async list(limit: number): Promise<Note[]> {
    const rows = await this.connection.db
      .select()
      .from(notes)
      .orderBy(desc(notes.id))
      .limit(limit);
    return rows.map(toNote);
  }
  async add(note: { author: string; body: string }): Promise<Note> {
    const [row] = await this.connection.db
      .insert(notes)
      .values({ ...note, createdAt: new Date() })
      .returning();
    if (!row) throw new Error('Insert returned no row');
    return toNote(row);
  }
  async count(): Promise<number> {
    const [row] = await this.connection.db
      .select({ value: count() })
      .from(notes);
    return row?.value ?? 0;
  }
  onModuleDestroy(): void {
    this.connection.client.close();
  }
}

function toNote(row: typeof notes.$inferSelect): Note {
  return {
    id: row.id,
    author: row.author,
    body: row.body,
    createdAt: row.createdAt.toISOString(),
  };
}

@Module({})
export class DatabaseModule {
  /** Opens the database file and applies pending migrations before the app starts. */
  static forRoot(options: { file: string }): DynamicModule {
    return {
      module: DatabaseModule,
      providers: [
        {
          provide: CONNECTION,
          useFactory: async (): Promise<Connection> => {
            const client = createClient({
              url: pathToFileURL(options.file).href,
            });
            const db = drizzle(client, { schema });
            await migrate(db, { migrationsFolder });
            return { client, db };
          },
        },
        { provide: NOTES_STORE, useClass: DrizzleNotesStore },
      ],
      exports: [NOTES_STORE],
    };
  }
}
