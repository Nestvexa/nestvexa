import { Action, Computed, LiveComponent, State } from 'nestvexa';
import type { LiveUpdateContext } from 'nestvexa';
import {
  createFormMeta,
  formView,
  visibleFields,
  zodAdapter,
} from '@nestvexa/forms';
import type { FormErrors, FormMeta } from '@nestvexa/forms';
import { validateField, validateLive } from '@nestvexa/forms/live';
import { z } from 'zod';

/** Product rules. The server always validates; browser attributes are conveniences. */
export const contactSchema = z.strictObject({
  name: z.string().trim().min(2, 'Enter at least 2 characters.').max(100),
  email: z.email('Enter a valid email address.'),
});
export const contactAdapter = zodAdapter(contactSchema);
export const contactFields = ['name', 'email'];
const text = (max: number) => ({
  writable: true as const,
  // Transport bound only; the schema owns the product rules.
  validate: (value: unknown) =>
    typeof value === 'string' && value.length <= max,
});

/** Generated by `nestvexa make:form`. Authorize "$mount", "$sync" and "submit". */
@LiveComponent({ name: 'contact-form', view: 'components/contact-form' })
export class ContactForm {
  @State(text(200)) name = '';
  @State(text(254)) email = '';
  /** Read-only: the server owns the error bag. */
  @State() errors: FormErrors = {};
  @State() form: FormMeta = createFormMeta();
  @State() status = '';

  @Computed() get fields() {
    return formView(this.errors, contactFields, {
      idPrefix: 'contact-',
      visible: visibleFields(this.form, contactFields),
    });
  }
  async afterUpdate(update: LiveUpdateContext): Promise<void> {
    await validateField(this, contactAdapter, contactFields, update.field, {
      metaField: 'form',
    });
  }
  @Action() async submit(): Promise<void> {
    const result = await validateLive(this, contactAdapter, contactFields, {
      metaField: 'form',
    });
    if (!result.ok) {
      this.status = '';
      return;
    }
    // result.value is typed by the schema. Persist it here.
    this.status = `Thanks, ${result.value.name}.`;
    this.form = createFormMeta();
  }
}
