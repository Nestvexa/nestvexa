import { UnauthorizedException } from '@nestjs/common';
import type { RealtimeModuleOptions } from '@nestvexa/realtime';
import { randomBytes } from 'node:crypto';

/** Channel prefixes any session may read; everything else is denied. */
export const publicChannels: readonly string[] = [
  // nestvexa:realtime-channels
];

/** HMAC signing secrets (at least 32 bytes). Required in production; never logged. */
export function realtimeSecrets(): string[] {
  const secret = process.env['REALTIME_SECRET'];
  if (secret !== undefined && Buffer.byteLength(secret) >= 32) return [secret];
  if (process.env['NODE_ENV'] === 'production')
    throw new Error('REALTIME_SECRET must be set to at least 32 bytes in production');
  return [randomBytes(32).toString('base64url')];
}

/** Generated by `nestvexa add realtime`. Replace the identity with your authentication. */
export const realtimeOptions: RealtimeModuleOptions = {
  secrets: realtimeSecrets(),
  origin: process.env['NESTVEXA_ORIGIN'] ?? 'http://localhost:3000',
  resolveIdentity: (request) => {
    const id: unknown = Reflect.get(request, 'sessionID');
    if (typeof id !== 'string') throw new UnauthorizedException();
    return { binding: `session:${id}` };
  },
  authorizeChannel: (_identity, channel) =>
    publicChannels.some((prefix) => channel === prefix || channel.startsWith(`${prefix}:`)),
};
