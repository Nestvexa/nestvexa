import { readFile, realpath, stat } from 'node:fs/promises';
import path from 'node:path';
import Handlebars from 'handlebars';
import {
  SafeHtml,
  ViewError,
  type RenderOptions,
  type ViewCapabilities,
  type ViewEngineAdapter,
  type ViewHelper,
  type ViewModel,
} from '@nestvexa/views';

export interface HbsOptions {
  readonly root: string;
  /** Production cache is bounded; deployment must call clearCache after replacing templates. */
  readonly cache?: boolean;
  readonly cacheEntries?: number;
  readonly maxTemplateBytes?: number;
  readonly defaultLayout?: string;
  /** Alias -> root-relative trusted template ID. No filesystem discovery or browser paths. */
  readonly partials?: Readonly<Record<string, string>>;
  readonly helpers?: Readonly<Record<string, ViewHelper>>;
  /** Trusted build-time module exports only. Presence disables filesystem fallback. */
  readonly precompiled?: HbsPrecompiledViews;
}
/** Executable specs generated by precompile(), never deserialized browser data. */
export type HbsPrecompiledViews = Readonly<Record<string, object>>;
const forbiddenKeys = new Set(['__proto__', 'prototype', 'constructor']);
const capabilities: ViewCapabilities = Object.freeze({
  layouts: true,
  partials: true,
  slots: true,
  asyncComposition: true,
  streaming: false,
  precompilation: true,
  safeHtml: true,
  viewComposers: true,
});

/** Copies only public data. Accessors are inspected without invoking them. */
function copyModel(
  value: unknown,
  active: Set<object>,
  budget: { nodes: number },
  depth = 0,
): unknown {
  if (++budget.nodes > 10_000 || depth > 32)
    throw new ViewError('UNSAFE_MODEL', 'View model exceeds structural limits');
  if (
    value === null ||
    value === undefined ||
    typeof value === 'string' ||
    typeof value === 'boolean'
  )
    return value;
  if (typeof value === 'number' && Number.isFinite(value)) return value;
  if (value instanceof SafeHtml) return new Handlebars.SafeString(value.value);
  if (typeof value !== 'object')
    throw new ViewError(
      'UNSAFE_MODEL',
      'Only finite JSON values and trusted HTML may enter a view',
    );
  if (active.has(value))
    throw new ViewError('UNSAFE_MODEL', 'Cyclic view model');
  const prototype: unknown = Object.getPrototypeOf(value);
  if (
    !Array.isArray(value) &&
    prototype !== Object.prototype &&
    prototype !== null
  )
    throw new ViewError(
      'UNSAFE_MODEL',
      'Class instances are not public view models',
    );
  if (Object.getOwnPropertySymbols(value).length)
    throw new ViewError('UNSAFE_MODEL', 'Symbol keys are unsupported');
  active.add(value);
  const output: Record<string, unknown> | unknown[] = Array.isArray(value)
    ? []
    : (Object.create(null) as Record<string, unknown>);
  for (const [key, descriptor] of Object.entries(
    Object.getOwnPropertyDescriptors(value),
  )) {
    if (Array.isArray(value) && key === 'length') continue;
    if (forbiddenKeys.has(key) || descriptor.get || descriptor.set)
      throw new ViewError('UNSAFE_MODEL', 'Unsafe view model property');
    if (!descriptor.enumerable) continue;
    Object.defineProperty(output, key, {
      value: copyModel(descriptor.value, active, budget, depth + 1),
      enumerable: true,
      writable: true,
      configurable: true,
    });
  }
  active.delete(value);
  return output;
}
function inside(root: string, filename: string): boolean {
  const relative = path.relative(root, filename);
  return (
    relative !== '' &&
    relative !== '..' &&
    !relative.startsWith(`..${path.sep}`) &&
    !path.isAbsolute(relative)
  );
}
/**
 * Controls, unpaired surrogates and noncharacters never name a template. They
 * are refused before any filesystem call: on Windows, Node 22/24 (libuv) abort
 * the whole process with a failed assertion for any path containing U+10FFFF.
 */
const unsafeViewCharacter = /[\p{Cc}\p{Cs}\p{Noncharacter_Code_Point}]/u;
function viewId(view: string): string {
  if (
    typeof view !== 'string' ||
    !view ||
    view.length > 240 ||
    view.includes('\\') ||
    view.includes(':') ||
    unsafeViewCharacter.test(view) ||
    path.posix.isAbsolute(view) ||
    view.split('/').some((part) => !part || part === '.' || part === '..')
  )
    throw new ViewError(
      'INVALID_VIEW',
      'View must be a root-relative forward-slash identifier',
    );
  return view.endsWith('.hbs') ? view : `${view}.hbs`;
}
function aliases<T>(value: Readonly<Record<string, T>>): void {
  for (const key of Object.keys(value))
    if (!/^[a-zA-Z][\w/-]*$/.test(key) || forbiddenKeys.has(key))
      throw new ViewError(
        'INVALID_VIEW',
        'Invalid helper, partial or slot alias',
      );
}

/** Each instance owns its Handlebars environment; no process-global helpers or data. */
export class HbsEngine implements ViewEngineAdapter {
  readonly name = 'hbs';
  readonly extensions = Object.freeze(['.hbs']);
  readonly capabilities = capabilities;
  readonly #hbs = Handlebars.create();
  readonly #cache = new Map<string, Handlebars.TemplateDelegate>();
  readonly #root: string;
  readonly #options: HbsOptions;
  readonly #cacheEntries: number;
  readonly #maxTemplateBytes: number;
  readonly #precompiled: Map<string, Handlebars.TemplateDelegate> | undefined;
  readonly #helpers = new Map<string, ViewHelper>();
  #helpersLocked = false;
  constructor(options: HbsOptions) {
    if (!options.root)
      throw new ViewError('INVALID_VIEW', 'A template root is required');
    this.#root = path.resolve(options.root);
    this.#cacheEntries = options.cacheEntries ?? 256;
    this.#maxTemplateBytes = options.maxTemplateBytes ?? 1_048_576;
    if (
      !Number.isSafeInteger(this.#cacheEntries) ||
      this.#cacheEntries < 1 ||
      !Number.isSafeInteger(this.#maxTemplateBytes) ||
      this.#maxTemplateBytes < 1
    )
      throw new ViewError(
        'INVALID_VIEW',
        'Template limits must be positive integers',
      );
    this.#options = Object.freeze({
      ...options,
      helpers: Object.freeze({ ...options.helpers }),
      partials: Object.freeze({ ...options.partials }),
    });
    aliases(this.#options.helpers ?? {});
    aliases(this.#options.partials ?? {});
    for (const [name, helper] of Object.entries(this.#options.helpers ?? {}))
      this.#helpers.set(name, helper);
    if (options.precompiled !== undefined) {
      this.#precompiled = new Map();
      for (const [view, spec] of Object.entries(options.precompiled)) {
        const id = viewId(view);
        if (this.#precompiled.has(id))
          throw new ViewError('INVALID_VIEW', 'Duplicate precompiled view');
        if (
          spec === null ||
          typeof spec !== 'object' ||
          typeof Object.getOwnPropertyDescriptor(spec, 'main')?.value !==
            'function'
        )
          throw new ViewError(
            'INVALID_VIEW',
            'Precompiled view must be a trusted executable Handlebars specification',
          );
        this.#precompiled.set(id, this.#hbs.template(spec));
      }
    }
  }
  /**
   * Add trusted engine-wide helpers (for example from the optional i18n or UI
   * kit packages) before initialize() or the first render. Names must be new;
   * the `nv` + uppercase prefix is reserved for framework helpers.
   */
  registerHelpers(helpers: Readonly<Record<string, ViewHelper>>): void {
    if (this.#helpersLocked)
      throw new ViewError(
        'INVALID_VIEW',
        'Helpers must be registered before initialize() or the first render',
      );
    const prototype: unknown =
      helpers !== null && typeof helpers === 'object'
        ? Object.getPrototypeOf(helpers)
        : undefined;
    if (
      Array.isArray(helpers) ||
      (prototype !== Object.prototype && prototype !== null)
    )
      throw new ViewError('INVALID_VIEW', 'Helpers must be a plain object');
    const additions = new Map<string, ViewHelper>();
    for (const key of Reflect.ownKeys(helpers)) {
      const descriptor = Object.getOwnPropertyDescriptor(helpers, key);
      const value: unknown = descriptor?.value;
      if (
        typeof key !== 'string' ||
        !descriptor?.enumerable ||
        !('value' in descriptor) ||
        typeof value !== 'function'
      )
        throw new ViewError(
          'INVALID_VIEW',
          'Helpers must be enumerable function data properties',
        );
      if (/^nv[A-Z]/.test(key))
        throw new ViewError('INVALID_VIEW', `Reserved helper name: ${key}`);
      if (this.#helpers.has(key))
        throw new ViewError('INVALID_VIEW', `Duplicate helper: ${key}`);
      additions.set(key, value as ViewHelper);
    }
    aliases(Object.fromEntries(additions));
    for (const [name, helper] of additions) this.#helpers.set(name, helper);
  }
  async initialize(): Promise<void> {
    this.#helpersLocked = true;
    if (this.#precompiled) return;
    if (!(await stat(this.#root)).isDirectory())
      throw new ViewError('INVALID_VIEW', 'Template root is not a directory');
  }
  clearCache(): void {
    this.#cache.clear();
  }
  async dispose(): Promise<void> {
    this.clearCache();
  }
  async #sourcePath(view: string): Promise<string> {
    const candidate = path.resolve(this.#root, viewId(view));
    if (!inside(this.#root, candidate))
      throw new ViewError('INVALID_VIEW', 'Template escapes root');
    const [root, filename] = await Promise.all([
      realpath(this.#root),
      realpath(candidate),
    ]);
    if (!inside(root, filename))
      throw new ViewError('INVALID_VIEW', 'Template symlink escapes root');
    return filename;
  }
  async #source(filename: string): Promise<string> {
    const info = await stat(filename);
    if (!info.isFile() || info.size > this.#maxTemplateBytes)
      throw new ViewError('INVALID_VIEW', 'Invalid or oversized template');
    const source = await readFile(filename, 'utf8');
    if (Buffer.byteLength(source) > this.#maxTemplateBytes)
      throw new ViewError('INVALID_VIEW', 'Oversized template');
    return source;
  }
  /** Returns deterministic ESM source; write as .mjs and statically import at deployment. */
  async precompile(views: readonly string[]): Promise<string> {
    const ids = views.map(viewId).sort();
    if (new Set(ids).size !== ids.length)
      throw new ViewError('INVALID_VIEW', 'Duplicate precompile view');
    const entries: string[] = [];
    for (const id of ids) {
      // Upstream types call this TemplateSpecification, but the documented runtime result is source text.
      const compiled: unknown = this.#hbs.precompile(
        await this.#source(await this.#sourcePath(id)),
      );
      if (typeof compiled !== 'string')
        throw new ViewError(
          'RENDER_FAILED',
          'Unsupported Handlebars precompiler output',
        );
      entries.push(`${JSON.stringify(id)}: Object.freeze(${compiled})`);
    }
    return `// Generated by Nestvexa using Handlebars ${this.#hbs.VERSION}. Trusted application code.\nexport default Object.freeze({\n${entries.join(',\n')}\n});\n`;
  }
  async #template(view: string): Promise<Handlebars.TemplateDelegate> {
    if (this.#precompiled) {
      const compiled = this.#precompiled.get(viewId(view));
      if (!compiled)
        throw new ViewError(
          'INVALID_VIEW',
          `View is absent from precompiled registry: ${view}`,
        );
      return compiled;
    }
    const filename = await this.#sourcePath(view);
    const cached = this.#options.cache ? this.#cache.get(filename) : undefined;
    if (cached) return cached;
    const source = await this.#source(filename);
    const compiled = this.#hbs.compile(source);
    if (this.#options.cache) {
      if (this.#cache.size >= this.#cacheEntries) {
        const oldest = this.#cache.keys().next().value;
        if (oldest !== undefined) this.#cache.delete(oldest);
      }
      this.#cache.set(filename, compiled);
    }
    return compiled;
  }
  async render(
    view: string,
    model: ViewModel,
    options: RenderOptions = {},
  ): Promise<string> {
    try {
      const safe = copyModel(model, new Set(), { nodes: 0 });
      if (safe === null || typeof safe !== 'object' || Array.isArray(safe))
        throw new ViewError('UNSAFE_MODEL', 'View model must be an object');
      this.#helpersLocked = true;
      const helpers = {
        ...Object.fromEntries(this.#helpers),
        ...options.helpers,
      };
      const partialFiles = { ...this.#options.partials, ...options.partials };
      aliases(helpers);
      aliases(partialFiles);
      aliases(options.slots ?? {});
      const partials: Record<string, Handlebars.TemplateDelegate> =
        Object.create(null) as Record<string, Handlebars.TemplateDelegate>;
      for (const [alias, file] of Object.entries(partialFiles))
        partials[alias] = await this.#template(file);
      const adaptedHelpers: Record<string, Handlebars.HelperDelegate> =
        Object.create(null) as Record<string, Handlebars.HelperDelegate>;
      for (const [name, helper] of Object.entries(helpers)) {
        const hbs = this.#hbs;
        // The Handlebars context is forwarded so trusted block helpers can
        // render their body with options.fn(this).
        adaptedHelpers[name] = function (this: unknown, ...args: unknown[]) {
          const result: unknown = Reflect.apply(helper, this, args);
          if (result instanceof Promise)
            throw new ViewError(
              'RENDER_FAILED',
              'Async helpers are unsupported; use a view composer',
            );
          return result instanceof SafeHtml
            ? new hbs.SafeString(result.value)
            : result;
        };
      }
      const runtime: Handlebars.RuntimeOptions = {
        helpers: adaptedHelpers,
        partials,
        allowProtoMethodsByDefault: false,
        allowProtoPropertiesByDefault: false,
        allowCallsToHelperMissing: false,
      };
      const context = {
        ...safe,
        slots: copyModel(options.slots ?? {}, new Set(), { nodes: 0 }),
      };
      const html = (await this.#template(view))(context, runtime);
      const layout = options.layout ?? this.#options.defaultLayout;
      return layout
        ? (await this.#template(layout))(
            { ...context, body: new this.#hbs.SafeString(html) },
            runtime,
          )
        : html;
    } catch (cause) {
      if (cause instanceof ViewError) throw cause;
      throw new ViewError('RENDER_FAILED', `Unable to render view: ${view}`, {
        cause,
      });
    }
  }
  /** Express engine bridge. Host settings and response locals metadata are not view data. */
  renderFile(
    filename: string,
    options: Record<string, unknown>,
    callback: (error: Error | null, html?: string) => void,
  ): void {
    if (!inside(this.#root, path.resolve(filename))) {
      callback(new ViewError('INVALID_VIEW', 'Template escapes root'));
      return;
    }
    const model: Record<string, unknown> = Object.create(null) as Record<
      string,
      unknown
    >;
    for (const [key, descriptor] of Object.entries(
      Object.getOwnPropertyDescriptors(options),
    )) {
      if (key === 'settings' || key === '_locals' || key === 'cache') continue;
      Object.defineProperty(model, key, descriptor);
    }
    const view = path.relative(this.#root, filename).split(path.sep).join('/');
    void this.render(view, model).then(
      (html) => callback(null, html),
      (error: unknown) =>
        callback(error instanceof Error ? error : new Error('Render failed')),
    );
  }
}
