import Handlebars from 'handlebars';
import {
  SafeHtml,
  TemplateRoot,
  ViewError,
  assertViewAliases,
  copyViewModel,
  expressViewModel,
  type RenderOptions,
  type ViewCapabilities,
  type ViewEngineAdapter,
  type ViewHelper,
  type ViewModel,
} from '@nestvexa/views';

export interface HbsOptions {
  /** Trusted template directory (operating-system path, Windows paths included). */
  readonly root: string;
  /** Production cache is bounded; deployment must call clearCache after replacing templates. */
  readonly cache?: boolean;
  readonly cacheEntries?: number;
  readonly maxTemplateBytes?: number;
  /** Template name/line in ViewError messages. Defaults to `!cache`. */
  readonly debug?: boolean;
  readonly defaultLayout?: string;
  /** Alias -> root-relative trusted template ID. No filesystem discovery or browser paths. */
  readonly partials?: Readonly<Record<string, string>>;
  readonly helpers?: Readonly<Record<string, ViewHelper>>;
  /** Namespace -> trusted directory, addressed as `admin::users/index`. */
  readonly namespaces?: Readonly<Record<string, string>>;
  /** Theme -> trusted override directory, selected per render with `RenderOptions.theme`. */
  readonly themes?: Readonly<Record<string, string>>;
  /** Trusted build-time module exports only. Presence disables filesystem fallback. */
  readonly precompiled?: HbsPrecompiledViews;
}
/** Executable specs generated by precompile(), never deserialized browser data. */
export type HbsPrecompiledViews = Readonly<Record<string, object>>;
const capabilities: ViewCapabilities = Object.freeze({
  layouts: true,
  partials: true,
  slots: true,
  asyncComposition: true,
  streaming: false,
  precompilation: true,
  safeHtml: true,
  viewComposers: true,
});
/** Layout inheritance: a layout starting with `{{!< parent}}` renders inside `parent`. */
const parentDirective = /^\s*\{\{!<\s*([^\s{}]+)\s*\}\}/;
/** Property carrying the parent layout of a precompiled layout specification. */
const parentProperty = 'nvParentLayout';
const maxLayoutDepth = 8;

interface HbsTemplate {
  readonly id: string;
  readonly render: Handlebars.TemplateDelegate;
  readonly parent: string | undefined;
  /** First source line of each partial reference, for missing-partial diagnostics. */
  readonly partialLines: ReadonlyMap<string, number>;
}
interface TemplateLocation {
  readonly template: string;
  readonly line: number | undefined;
}
/** Source-load failure (parse error) located in a template. */
class TemplateLoadError extends Error {
  constructor(
    readonly location: TemplateLocation,
    options: ErrorOptions,
  ) {
    super('Template could not be compiled', options);
  }
}
/** Per-render execution trace: the template stack and the innermost failure. */
interface Trace {
  readonly stack: string[];
  failure: TemplateLocation | undefined;
}

function lineOf(value: unknown): number | undefined {
  if (value === null || typeof value !== 'object') return undefined;
  const loc: unknown = Reflect.get(value, 'loc');
  if (loc === null || typeof loc !== 'object') return undefined;
  const start: unknown = Reflect.get(loc, 'start');
  if (start === null || typeof start !== 'object') return undefined;
  const line: unknown = Reflect.get(start, 'line');
  return typeof line === 'number' && Number.isSafeInteger(line)
    ? line
    : undefined;
}
/** Collects `{{> name}}` source lines by walking the parsed AST. */
function partialLines(program: hbs.AST.Program): ReadonlyMap<string, number> {
  const lines = new Map<string, number>();
  const visit = (node: unknown, depth: number): void => {
    if (depth > 256 || node === null || typeof node !== 'object') return;
    if (Array.isArray(node)) {
      for (const child of node as readonly unknown[]) visit(child, depth + 1);
      return;
    }
    const type: unknown = Reflect.get(node, 'type');
    if (type === 'PartialStatement' || type === 'PartialBlockStatement') {
      const name: unknown = Reflect.get(node, 'name');
      const original: unknown =
        name !== null && typeof name === 'object'
          ? Reflect.get(name, 'original')
          : undefined;
      const line = lineOf(node);
      if (typeof original === 'string' && line !== undefined)
        if (!lines.has(original)) lines.set(original, line);
    }
    for (const key of ['body', 'program', 'inverse'])
      visit(Reflect.get(node, key), depth + 1);
  };
  visit(program, 0);
  return lines;
}
function handlebarsLine(error: unknown): number | undefined {
  if (!(error instanceof Error)) return undefined;
  const line: unknown = Reflect.get(error, 'lineNumber');
  if (typeof line === 'number' && Number.isSafeInteger(line)) return line;
  const parse = /^Parse error on line (\d+):/.exec(error.message);
  return parse?.[1] ? Number(parse[1]) : undefined;
}

/** Each instance owns its Handlebars environment; no process-global helpers or data. */
export class HbsEngine implements ViewEngineAdapter {
  readonly name = 'hbs';
  readonly extensions = Object.freeze(['.hbs']);
  readonly capabilities = capabilities;
  readonly #hbs = Handlebars.create();
  readonly #cache = new Map<string, HbsTemplate>();
  readonly #root: TemplateRoot;
  readonly #options: HbsOptions;
  readonly #cacheEntries: number;
  readonly #debug: boolean;
  readonly #precompiled: Map<string, HbsTemplate> | undefined;
  readonly #helpers = new Map<string, ViewHelper>();
  #helpersLocked = false;
  constructor(options: HbsOptions) {
    this.#root = new TemplateRoot({
      root: options.root,
      extension: '.hbs',
      ...(options.maxTemplateBytes === undefined
        ? {}
        : { maxTemplateBytes: options.maxTemplateBytes }),
      ...(options.namespaces === undefined
        ? {}
        : { namespaces: options.namespaces }),
      ...(options.themes === undefined ? {} : { themes: options.themes }),
    });
    this.#cacheEntries = options.cacheEntries ?? 256;
    if (!Number.isSafeInteger(this.#cacheEntries) || this.#cacheEntries < 1)
      throw new ViewError(
        'INVALID_VIEW',
        'Template limits must be positive integers',
      );
    this.#debug = options.debug ?? !options.cache;
    this.#options = Object.freeze({
      ...options,
      helpers: Object.freeze({ ...options.helpers }),
      partials: Object.freeze({ ...options.partials }),
    });
    assertViewAliases(this.#options.helpers ?? {});
    assertViewAliases(this.#options.partials ?? {});
    for (const [name, helper] of Object.entries(this.#options.helpers ?? {}))
      this.#helpers.set(name, helper);
    if (options.precompiled !== undefined) {
      this.#precompiled = new Map();
      for (const [view, spec] of Object.entries(options.precompiled)) {
        const id = this.#root.id(view);
        if (this.#precompiled.has(id))
          throw new ViewError('INVALID_VIEW', 'Duplicate precompiled view');
        if (
          spec === null ||
          typeof spec !== 'object' ||
          typeof Object.getOwnPropertyDescriptor(spec, 'main')?.value !==
            'function'
        )
          throw new ViewError(
            'INVALID_VIEW',
            'Precompiled view must be a trusted executable Handlebars specification',
          );
        const parent: unknown = Object.getOwnPropertyDescriptor(
          spec,
          parentProperty,
        )?.value;
        if (parent !== undefined && typeof parent !== 'string')
          throw new ViewError('INVALID_VIEW', 'Invalid precompiled layout');
        this.#precompiled.set(
          id,
          Object.freeze({
            id,
            render: this.#hbs.template(spec),
            parent: parent === undefined ? undefined : this.#root.id(parent),
            partialLines: new Map(),
          }),
        );
      }
    }
  }
  /**
   * Add trusted engine-wide helpers (for example from the optional i18n or UI
   * kit packages) before initialize() or the first render. Names must be new;
   * the `nv` + uppercase prefix is reserved for framework helpers.
   */
  registerHelpers(helpers: Readonly<Record<string, ViewHelper>>): void {
    if (this.#helpersLocked)
      throw new ViewError(
        'INVALID_VIEW',
        'Helpers must be registered before initialize() or the first render',
      );
    const prototype: unknown =
      helpers !== null && typeof helpers === 'object'
        ? Object.getPrototypeOf(helpers)
        : undefined;
    if (
      Array.isArray(helpers) ||
      (prototype !== Object.prototype && prototype !== null)
    )
      throw new ViewError('INVALID_VIEW', 'Helpers must be a plain object');
    const additions = new Map<string, ViewHelper>();
    for (const key of Reflect.ownKeys(helpers)) {
      const descriptor = Object.getOwnPropertyDescriptor(helpers, key);
      const value: unknown = descriptor?.value;
      if (
        typeof key !== 'string' ||
        !descriptor?.enumerable ||
        !('value' in descriptor) ||
        typeof value !== 'function'
      )
        throw new ViewError(
          'INVALID_VIEW',
          'Helpers must be enumerable function data properties',
        );
      if (/^nv[A-Z]/.test(key))
        throw new ViewError('INVALID_VIEW', `Reserved helper name: ${key}`);
      if (this.#helpers.has(key))
        throw new ViewError('INVALID_VIEW', `Duplicate helper: ${key}`);
      additions.set(key, value as ViewHelper);
    }
    assertViewAliases(Object.fromEntries(additions));
    for (const [name, helper] of additions) this.#helpers.set(name, helper);
  }
  async initialize(): Promise<void> {
    this.#helpersLocked = true;
    if (this.#precompiled) return;
    await this.#root.assertDirectory();
  }
  clearCache(): void {
    this.#cache.clear();
  }
  async dispose(): Promise<void> {
    this.clearCache();
  }
  /** Parses eagerly so syntax errors name their template and line. */
  #compile(
    id: string,
    source: string,
  ): {
    program: hbs.AST.Program;
    parent: string | undefined;
  } {
    let program: hbs.AST.Program;
    try {
      program = this.#hbs.parse(source);
    } catch (cause) {
      throw new TemplateLoadError(
        { template: id, line: handlebarsLine(cause) },
        { cause },
      );
    }
    const directive = parentDirective.exec(source)?.[1];
    return {
      program,
      parent: directive === undefined ? undefined : this.#root.id(directive),
    };
  }
  /** Returns deterministic ESM source; write as .mjs and statically import at deployment. */
  async precompile(views: readonly string[]): Promise<string> {
    const ids = views.map((view) => this.#root.id(view)).sort();
    if (new Set(ids).size !== ids.length)
      throw new ViewError('INVALID_VIEW', 'Duplicate precompile view');
    const entries: string[] = [];
    for (const id of ids) {
      const source = await this.#root.read(await this.#root.resolve(id));
      const { program, parent } = this.#compile(id, source);
      // Upstream types call this TemplateSpecification, but the documented runtime result is source text.
      const compiled: unknown = this.#hbs.precompile(program);
      if (typeof compiled !== 'string')
        throw new ViewError(
          'RENDER_FAILED',
          'Unsupported Handlebars precompiler output',
        );
      const spec =
        parent === undefined
          ? compiled
          : `Object.assign(${compiled}, { ${parentProperty}: ${JSON.stringify(parent)} })`;
      entries.push(`${JSON.stringify(id)}: Object.freeze(${spec})`);
    }
    return `// Generated by Nestvexa using Handlebars ${this.#hbs.VERSION}. Trusted application code.\nexport default Object.freeze({\n${entries.join(',\n')}\n});\n`;
  }
  async #template(
    view: string,
    theme: string | undefined,
  ): Promise<HbsTemplate> {
    if (this.#precompiled) {
      if (theme !== undefined)
        throw new ViewError(
          'UNSUPPORTED_CAPABILITY',
          'Themes need source templates; precompiled views have no override directories',
        );
      const compiled = this.#precompiled.get(this.#root.id(view));
      if (!compiled)
        throw new ViewError(
          'INVALID_VIEW',
          `View is absent from precompiled registry: ${view}`,
        );
      return compiled;
    }
    const id = this.#root.id(view);
    const filename = await this.#root.resolve(id, undefined, theme);
    const cached = this.#options.cache ? this.#cache.get(filename) : undefined;
    if (cached) return cached;
    const { program, parent } = this.#compile(
      id,
      await this.#root.read(filename),
    );
    const template: HbsTemplate = Object.freeze({
      id,
      render: this.#hbs.compile(program),
      parent,
      partialLines: partialLines(program),
    });
    if (this.#options.cache) {
      if (this.#cache.size >= this.#cacheEntries) {
        const oldest = this.#cache.keys().next().value;
        if (oldest !== undefined) this.#cache.delete(oldest);
      }
      this.#cache.set(filename, template);
    }
    return template;
  }
  async render(
    view: string,
    model: ViewModel,
    options: RenderOptions = {},
  ): Promise<string> {
    const trace: Trace = { stack: [], failure: undefined };
    try {
      const hbs = this.#hbs;
      const theme = this.#root.theme(options.theme);
      const safe = copyViewModel(
        model,
        (html: SafeHtml) => new hbs.SafeString(html.value),
      );
      this.#helpersLocked = true;
      const helpers = {
        ...Object.fromEntries(this.#helpers),
        ...options.helpers,
      };
      const partialFiles = { ...this.#options.partials, ...options.partials };
      assertViewAliases(helpers);
      assertViewAliases(partialFiles);
      assertViewAliases(options.slots ?? {});
      const located = (helper: (...args: unknown[]) => unknown) =>
        function (this: unknown, ...args: unknown[]): unknown {
          try {
            return Reflect.apply(helper, this, args);
          } catch (error) {
            // The innermost helper records first; outer helpers keep its location.
            trace.failure ??= {
              template: trace.stack.at(-1) ?? view,
              line: lineOf(args.at(-1)),
            };
            throw error;
          }
        };
      const invoke = (
        template: HbsTemplate,
        context: unknown,
        runtime: Handlebars.RuntimeOptions,
      ): string => {
        trace.stack.push(template.id);
        try {
          return template.render(context, runtime);
        } catch (error) {
          const missing =
            error instanceof Error
              ? /^The partial (.+) could not be found$/.exec(error.message)?.[1]
              : undefined;
          trace.failure ??= {
            template: template.id,
            line:
              handlebarsLine(error) ??
              (missing === undefined
                ? undefined
                : template.partialLines.get(missing)),
          };
          throw error;
        } finally {
          trace.stack.pop();
        }
      };
      const partials: Record<string, Handlebars.TemplateDelegate> =
        Object.create(null) as Record<string, Handlebars.TemplateDelegate>;
      for (const [alias, file] of Object.entries(partialFiles)) {
        const template = await this.#template(file, theme);
        // Partials receive Handlebars' own options (data, block params, helpers).
        partials[alias] = (
          context: unknown,
          runtime?: Handlebars.RuntimeOptions,
        ) => invoke(template, context, runtime ?? {});
      }
      const adaptedHelpers: Record<string, Handlebars.HelperDelegate> =
        Object.create(null) as Record<string, Handlebars.HelperDelegate>;
      // Built-in helpers are wrapped only to locate their errors.
      for (const [name, helper] of Object.entries(hbs.helpers))
        if (typeof helper === 'function')
          adaptedHelpers[name] = located(
            helper as (...args: unknown[]) => unknown,
          );
      adaptedHelpers['helperMissing'] = located((...args: unknown[]) => {
        // A lone options argument is a plain missing value, rendered empty.
        if (args.length <= 1) return undefined;
        const options = args.at(-1);
        const name: unknown =
          options !== null && typeof options === 'object'
            ? Reflect.get(options, 'name')
            : undefined;
        throw new Error(
          `Missing helper: ${typeof name === 'string' ? name : 'unknown'}`,
        );
      });
      for (const [name, helper] of Object.entries(helpers)) {
        // The Handlebars context is forwarded so trusted block helpers can
        // render their body with options.fn(this).
        adaptedHelpers[name] = located(function (
          this: unknown,
          ...args: unknown[]
        ) {
          const result: unknown = Reflect.apply(helper, this, args);
          if (result instanceof Promise)
            throw new ViewError(
              'RENDER_FAILED',
              'Async helpers are unsupported; use a view composer',
            );
          return result instanceof SafeHtml
            ? new hbs.SafeString(result.value)
            : result;
        });
      }
      const runtime: Handlebars.RuntimeOptions = {
        helpers: adaptedHelpers,
        partials,
        allowProtoMethodsByDefault: false,
        allowProtoPropertiesByDefault: false,
        allowCallsToHelperMissing: false,
      };
      const context = {
        ...safe,
        slots: copyViewModel(
          options.slots ?? {},
          (html: SafeHtml) => new hbs.SafeString(html.value),
        ),
      };
      let html = invoke(await this.#template(view, theme), context, runtime);
      let layout = options.layout ?? this.#options.defaultLayout;
      const seen = new Set<string>();
      while (layout) {
        const template = await this.#template(layout, theme);
        if (seen.has(template.id) || seen.size >= maxLayoutDepth)
          throw new ViewError(
            'INVALID_VIEW',
            `Layout inheritance cycle or depth over ${maxLayoutDepth}: ${template.id}`,
          );
        seen.add(template.id);
        html = invoke(
          template,
          { ...context, body: new hbs.SafeString(html) },
          runtime,
        );
        layout = template.parent;
      }
      return html;
    } catch (thrown) {
      const location =
        thrown instanceof TemplateLoadError ? thrown.location : trace.failure;
      const cause = thrown instanceof TemplateLoadError ? thrown.cause : thrown;
      if (cause instanceof ViewError && cause.code !== 'RENDER_FAILED')
        throw cause;
      if (cause instanceof ViewError && !this.#debug) throw cause;
      throw new ViewError('RENDER_FAILED', this.#failure(view, location), {
        cause,
      });
    }
  }
  #failure(view: string, location: TemplateLocation | undefined): string {
    const base = `Unable to render view: ${view}`;
    if (!this.#debug || !location) return base;
    return location.line === undefined
      ? `${base} (${location.template})`
      : `${base} (${location.template}:${location.line})`;
  }
  /** Express engine bridge. Host settings and response locals metadata are not view data. */
  renderFile(
    filename: string,
    options: Record<string, unknown>,
    callback: (error: Error | null, html?: string) => void,
  ): void {
    const view = this.#root.viewFromFile(filename);
    if (view === undefined) {
      callback(new ViewError('INVALID_VIEW', 'Template escapes root'));
      return;
    }
    void this.render(view, expressViewModel(options)).then(
      (html) => callback(null, html),
      (error: unknown) =>
        callback(error instanceof Error ? error : new Error('Render failed')),
    );
  }
}
