type Mode = 'input' | 'output' | 'output-top';

function createProgram(
  options: GenerateActionClientOptions,
  diagnostics: ActionCodegenDiagnostic[],
): ts.Program | undefined {
  const defaults: ts.CompilerOptions = {
    target: ts.ScriptTarget.ES2022,
    module: ts.ModuleKind.NodeNext,
    moduleResolution: ts.ModuleResolutionKind.NodeNext,
    experimentalDecorators: true,
    emitDecoratorMetadata: true,
    strict: true,
    skipLibCheck: true,
  };
  const format = (diagnostic: ts.Diagnostic) =>
    ts.flattenDiagnosticMessageText(diagnostic.messageText, '\n');
  if (options.project !== undefined) {
    const project = resolve(options.project);
    const read = ts.readConfigFile(project, (path) => ts.sys.readFile(path));
    if (read.error) {
      diagnostics.push({
        severity: 'error',
        message: format(read.error),
        file: project,
      });
      return undefined;
    }
    const parsed = ts.parseJsonConfigFileContent(
      read.config,
      ts.sys,
      dirname(project),
      undefined,
      project,
    );
    for (const error of parsed.errors)
      diagnostics.push({
        severity: 'error',
        message: format(error),
        file: project,
      });
    if (parsed.errors.length > 0) return undefined;
    return ts.createProgram({
      rootNames: [...parsed.fileNames].sort(),
      options: {
        ...parsed.options,
        noEmit: true,
        incremental: false,
        composite: false,
      },
    });
  }
  if (!options.files || options.files.length === 0) {
    diagnostics.push({
      severity: 'error',
      message: 'Pass a tsconfig project or at least one source file',
    });
    return undefined;
  }
  return ts.createProgram({
    rootNames: options.files.map((file) => resolve(file)).sort(),
    options: { ...defaults, ...options.compilerOptions, noEmit: true },
  });
}

/** Generates `<outDir>/<fileName>.js` and `.d.ts`. Never writes when errors are reported. */
export async function generateActionClient(
  options: GenerateActionClientOptions,
): Promise<GenerateActionClientResult> {
  const diagnostics: ActionCodegenDiagnostic[] = [];
  const fileName = options.fileName ?? 'actions-client';
  if (!/^[A-Za-z0-9._-]{1,128}$/.test(fileName) || fileName.startsWith('.'))
    throw new Error('Invalid generated file name');
  const clientModule = options.clientModule ?? '@nestvexa/actions/client';
  if (!/^[@A-Za-z0-9._/-]{1,256}$/.test(clientModule))
    throw new Error('Invalid client module specifier');
  const targets = [...new Set(options.targets ?? [])].sort();
  for (const target of targets)
    if (!TARGETS.includes(target))
      throw new Error(`Unknown codegen target ${String(target)}`);
  const program = createProgram(options, diagnostics);
  if (!program) return { ok: false, files: [], diagnostics, groups: [] };
  const cwd = process.cwd();
  for (const diagnostic of program.getSyntacticDiagnostics())
    diagnostics.push({
      severity: 'error',
      message: ts.flattenDiagnosticMessageText(diagnostic.messageText, '\n'),
      ...(diagnostic.file
        ? { file: relative(cwd, diagnostic.file.fileName).replace(/\\/g, '/') }
        : {}),
    });
  const generator = new Generator(program, cwd);
  const groups = generator.collect();
  const { js, dts, bindings } = generator.render(groups, clientModule);
  diagnostics.push(...generator.diagnostics);
  const outDir = resolve(options.outDir);
  const outputs = [
    { path: join(outDir, `${fileName}.js`), contents: js },
    { path: join(outDir, `${fileName}.d.ts`), contents: dts },
  ];
  for (const target of targets) {
    const rendered = renderTarget(
      target,
      bindings,
      clientModule,
      `./${fileName}.js`,
    );
    outputs.push(
      { path: join(outDir, `${fileName}.${target}.js`), contents: rendered.js },
      {
        path: join(outDir, `${fileName}.${target}.d.ts`),
        contents: rendered.dts,
      },
    );
  }
  const files: GeneratedActionFile[] = [];
  for (const output of outputs) {
    let current: string | undefined;
    try {
      current = await readFile(output.path, 'utf8');
    } catch {
      current = undefined;
    }
    files.push({ ...output, changed: current !== output.contents });
  }
  if (options.check)
    for (const file of files)
      if (file.changed)
        diagnostics.push({
          severity: 'error',
          message: `${relative(cwd, file.path).replace(/\\/g, '/')} is out of date; rerun nestvexa-actions-codegen`,
        });
  const ok = !diagnostics.some((diagnostic) => diagnostic.severity === 'error');
  if (ok && options.write !== false && !options.check)
    for (const file of files)
      if (file.changed) {
        await mkdir(dirname(file.path), { recursive: true });
        await writeFile(file.path, file.contents, 'utf8');
      }
  return {
    ok,
    files,
    diagnostics,
    groups: groups.map((group) => ({
      id: group.id,
      key: group.key,
      className: group.className,
      actions: group.actions.map((action) => ({
        id: action.id,
        version: action.version,
        key: action.key,
        method: action.method,
        idempotent: action.idempotent,
      })),
    })),
  };
}

export function formatDiagnostic(diagnostic: ActionCodegenDiagnostic): string {
  const location = diagnostic.file
    ? `${diagnostic.file}${diagnostic.line === undefined ? '' : `:${diagnostic.line}:${diagnostic.column ?? 1}`} - `
    : '';
  return `${location}${diagnostic.severity}: ${diagnostic.message}`;
}
