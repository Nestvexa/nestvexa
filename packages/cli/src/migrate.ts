/**
 * A versioned, reversible migration step. `detect` decides from the project
 * itself (never from version strings alone) whether the step applies; `up`
 * records AST-based file edits and manifest edits on the plan. File edits are
 * reverted from the backup recorded at apply time, manifest edits by `down`.
 */
export interface MigrationStep {
  /** Sortable id, `NNNN-description`. */
  readonly id: string;
  /** CLI version that introduced the step. */
  readonly introducedIn: string;
  readonly description: string;
  detect(project: ProjectInfo, manifest: Manifest): boolean;
  up(plan: ChangePlan, project: ProjectInfo, manifest: Manifest): string[];
  /** Undo manifest edits (file edits are restored from the backup). */
  down?(manifest: Manifest): void;
}

const oldSecret = new Set([
  "process.env['SESSION_SECRET']??randomBytes(48).toString('base64url')",
  'process.env["SESSION_SECRET"]??randomBytes(48).toString("base64url")',
  "process.env.SESSION_SECRET??randomBytes(48).toString('base64url')",
]);
function parse(text: string): ts.SourceFile {
  return ts.createSourceFile(
    'main.ts',
    text,
    ts.ScriptTarget.Latest,
    true,
    ts.ScriptKind.TS,
  );
}
/** `secret: <first-alpha init expression>` property initializers in main.ts. */
function legacySecrets(text: string): ts.Expression[] {
  const source = parse(text);
  const found: ts.Expression[] = [];
  const visit = (node: ts.Node): void => {
    if (
      ts.isPropertyAssignment(node) &&
      ts.isIdentifier(node.name) &&
      node.name.text === 'secret' &&
      oldSecret.has(node.initializer.getText(source).replace(/\s+/g, ''))
    )
      found.push(node.initializer);
    ts.forEachChild(node, visit);
  };
  visit(source);
  return found;
}
/** Remove a named import binding when nothing else in the file references it. */
export function removeUnusedImport(
  text: string,
  module: string,
  name: string,
): string {
  const source = parse(text);
  let uses = 0;
  const visit = (node: ts.Node): void => {
    if (
      ts.isIdentifier(node) &&
      node.text === name &&
      !ts.isImportSpecifier(node.parent)
    )
      uses++;
    ts.forEachChild(node, visit);
  };
  visit(source);
  if (uses) return text;
  for (const statement of source.statements) {
    if (
      !ts.isImportDeclaration(statement) ||
      !ts.isStringLiteral(statement.moduleSpecifier) ||
      statement.moduleSpecifier.text !== module
    )
      continue;
    const bindings = statement.importClause?.namedBindings;
    if (!bindings || !ts.isNamedImports(bindings)) continue;
    const element = bindings.elements.find((item) => item.name.text === name);
    if (!element) continue;
    if (bindings.elements.length === 1 && !statement.importClause?.name) {
      const end =
        text[statement.getEnd()] === '\n'
          ? statement.getEnd() + 1
          : statement.getEnd();
      return text.slice(0, statement.getStart(source)) + text.slice(end);
    }
    const rest = bindings.elements
      .filter((item) => item !== element)
      .map((item) => item.getText(source));
    return `${text.slice(0, bindings.getStart(source))}{ ${rest.join(', ')} }${text.slice(bindings.getEnd())}`;
  }
  return text;
}

export const migrations: readonly MigrationStep[] = Object.freeze([
  {
    id: '0001-manifest-v2',
    introducedIn: '0.1.0-alpha.1',
    description:
      'Upgrade .nestvexa/manifest.json to version 2 (template metadata and the migration log).',
    detect: (_project, manifest) => manifest.version === 1,
    up(plan) {
      plan.editManifest((manifest) => {
        manifest.version = 2;
        // Keys were always written with forward slashes; normalize defensively.
        manifest.files = Object.fromEntries(
          Object.entries(manifest.files).map(([path, entry]) => [
            toPosix(path),
            entry,
          ]),
        );
      });
      return [`${manifestPath}: version 1 → 2`];
    },
    down(manifest) {
      manifest.version = 1;
    },
  },
  {
    id: '0002-session-secret-required-in-production',
    introducedIn: '0.1.0-alpha.1',
    description:
      'main.ts generated by the first alpha `init` fell back to a random session secret in production; use sessionSecret(), which requires SESSION_SECRET (≥ 32 characters) when NODE_ENV=production.',
    detect(project) {
      const main = readText(project, project.mainFile);
      return main !== undefined && legacySecrets(main).length > 0;
    },
    up(plan, project) {
      const main = plan.read(project.mainFile) ?? '';
      const config = liveConfigPath(project);
      const configText = plan.read(config);
      if (configText === undefined)
        throw new CliError(
          `0002 needs ${config} (generated by init) to host sessionSecret(); replace the session secret in ${project.mainFile} manually.`,
        );
      let next = main;
      for (const expression of legacySecrets(main).reverse())
        next = `${next.slice(0, expression.getStart())}sessionSecret()${next.slice(expression.getEnd())}`;
      next = ensureImport(
        next,
        relativeImport(project.mainFile, config, project.esm),
        ['sessionSecret'],
      );
      next = removeUnusedImport(next, 'node:crypto', 'randomBytes');
      plan.update(project.mainFile, next);
      const notes = [`${project.mainFile}: session secret → sessionSecret()`];
      if (!/export function sessionSecret\(/.test(configText)) {
        let updated = configText.replace(
          /\nexport const nestvexaOptions/,
          `\n${sessionSecretSource}\nexport const nestvexaOptions`,
        );
        if (updated === configText)
          updated = `${configText.trimEnd()}\n\n${sessionSecretSource}`;
        plan.update(
          config,
          ensureImport(updated, 'node:crypto', ['randomBytes']),
        );
        notes.push(`${config}: added sessionSecret()`);
      }
      return notes;
    },
  },
]);

function readText(project: ProjectInfo, path: string): string | undefined {
  const absolute = projectPath(project.root, path);
  return existsSync(absolute) ? readFileSync(absolute, 'utf8') : undefined;
}
interface Backup {
  readonly id: string;
  readonly appliedAt: string;
  readonly files: readonly {
    path: string;
    before: string | null;
    after: string | null;
  }[];
}
const backupPath = (id: string) => `.nestvexa/migrations/${id}.json`;
function readBackup(project: ProjectInfo, id: string): Backup {
  const text = readText(project, backupPath(id));
  if (text === undefined)
    throw new CliError(`No backup recorded for migration ${id}`);
  const parsed: unknown = JSON.parse(text);
  const files: unknown =
    parsed && typeof parsed === 'object'
      ? Reflect.get(parsed, 'files')
      : undefined;
  if (!Array.isArray(files)) throw new CliError(`${backupPath(id)} is invalid`);
  return {
    id,
    appliedAt: String(Reflect.get(parsed as object, 'appliedAt')),
    files: (files as unknown[]).map((item) => {
      const path: unknown =
        item && typeof item === 'object'
          ? Reflect.get(item, 'path')
          : undefined;
      const before: unknown =
        item && typeof item === 'object'
          ? Reflect.get(item, 'before')
          : undefined;
      const after: unknown =
        item && typeof item === 'object'
          ? Reflect.get(item, 'after')
          : undefined;
      if (
        typeof path !== 'string' ||
        (before !== null && typeof before !== 'string') ||
        (after !== null && typeof after !== 'string')
      )
        throw new CliError(`${backupPath(id)} is invalid`);
      return { path, before, after };
    }),
  };
}

/**
 * `nestvexa migrate [--dry-run] [--json] [--revert <id>] [--force]`: applies
 * pending steps in id order inside one atomic plan, records each in the
 * manifest log with a backup of every file it changed, or reverts the most
 * recent step (refusing when the files were edited since, unless --force).
 */
export function migrate(context: CommandContext): CommandResult {
  const project = detectProject(context.cwd);
  const revert = context.options['revert'];
  if (typeof revert === 'string') return revertStep(context, project, revert);
  if (revert === true)
    throw new CliError('Usage: nestvexa migrate --revert <id>', 2);
  const manifest = readManifest(project.root);
  const applied = new Set(manifest.migrations.map((record) => record.id));
  const pending = migrations.filter(
    (step) => !applied.has(step.id) && step.detect(project, manifest),
  );
  const from = manifest.cli ?? project.dependencies['nestvexa'] ?? 'unknown';
  const data = {
    from,
    to: version,
    manifestVersion: manifest.version,
    applied: manifest.migrations,
    pending: pending.map(({ id, introducedIn, description }) => ({
      id,
      introducedIn,
      description,
    })),
  };
  if (!pending.length)
    return {
      ok: true,
      messages: [
        `Up to date: no migrations pending for ${version} (${manifest.migrations.length} applied).`,
      ],
      data,
    };
  const plan = newPlan(project, 'migrate');
  const appliedAt = new Date().toISOString();
  const messages: string[] = [];
  for (const step of pending) {
    const before = new Map(
      plan.changes.map((change) => [change.path, change.content]),
    );
    const notes = step.up(plan, project, manifest);
    const files = plan.changes
      .filter(
        (change) =>
          !before.has(change.path) ||
          change.content !== before.get(change.path),
      )
      .map((change) => ({
        path: change.path,
        // Disk content until apply; an earlier step's output when chained.
        before: before.has(change.path)
          ? (before.get(change.path) ?? null)
          : (readText(project, change.path) ?? null),
        after: change.content === undefined ? null : sha256(change.content),
      }));
    plan.create(
      backupPath(step.id),
      JSON.stringify({ id: step.id, appliedAt, files }, null, 2) + '\n',
      { force: true },
    );
    plan.editManifest((target) => {
      target.migrations.push({ id: step.id, appliedAt, cli: version });
    });
    messages.push(
      `${step.id}: ${step.description}`,
      ...notes.map((note) => `  ${note}`),
    );
  }
  return finish(
    plan,
    context,
    [
      ...messages,
      `Applied ${pending.length} migration(s). Revert the latest with \`nestvexa migrate --revert <id>\`.`,
    ],
    data,
  );
}

function revertStep(
  context: CommandContext,
  project: ProjectInfo,
  id: string,
): CommandResult {
  const manifest = readManifest(project.root);
  const latest = manifest.migrations.at(-1);
  if (!manifest.migrations.some((record) => record.id === id))
    throw new CliError(`Migration ${id} is not applied`);
  if (latest?.id !== id)
    throw new CliError(
      `Revert ${latest?.id ?? ''} first: migrations are reverted newest first`,
    );
  const step = migrations.find((item) => item.id === id);
  const backup = readBackup(project, id);
  const plan = newPlan(project, 'migrate');
  const edited: string[] = [];
  for (const file of backup.files) {
    const current = readText(project, file.path);
    const now = current === undefined ? null : sha256(current);
    if (now !== file.after) edited.push(file.path);
  }
  if (edited.length && !context.force)
    throw new CliError(
      `Refusing to revert ${id}: changed since the migration: ${edited.join(', ')}. Re-run with --force to restore the pre-migration files anyway.`,
    );
  for (const file of backup.files)
    if (file.before === null) plan.delete(file.path);
    else if (plan.exists(file.path)) plan.update(file.path, file.before);
    else plan.create(file.path, file.before, { force: true });
  plan.delete(backupPath(id));
  plan.editManifest((target) => {
    target.migrations = target.migrations.filter((record) => record.id !== id);
    step?.down?.(target);
  });
  return finish(plan, context, [`Reverted ${id}.`]);
}
