export const sessionSecretSource = `/**
 * Session signing secret: SESSION_SECRET (at least 32 characters) is required in
 * production; development falls back to a per-process random secret.
 */
export function sessionSecret(): string {
  const secret = process.env['SESSION_SECRET'];
  if (secret !== undefined && secret.length >= 32) return secret;
  if (process.env['NODE_ENV'] === 'production')
    throw new Error('SESSION_SECRET must be set to at least 32 characters in production');
  return randomBytes(48).toString('base64url');
}
`;
export type Platform = 'express' | 'fastify';
/**
 * The guest session id as an `unknown` expression (needs a `session` local):
 * express-session exposes `request.sessionID`, @fastify/session
 * `request.session.sessionId`. Both keep the CSRF token as a session property.
 */
export function sessionIdExpression(platform: Platform): string {
  return platform === 'fastify'
    ? "session && typeof session === 'object' ? Reflect.get(session, 'sessionId') : undefined"
    : "Reflect.get(request, 'sessionID')";
}
function sessionOwner(platform: Platform): string {
  return platform === 'fastify'
    ? '@fastify/session guest session\n * registered by session.ts'
    : 'express-session guest session\n * created in main.ts';
}
