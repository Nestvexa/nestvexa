export function fastifySession(esm: boolean): string {
  const ext = esm ? '.js' : '';
  return `import type { INestApplication } from '@nestjs/common';
import fastifyCookie from '@fastify/cookie';
import fastifySession from '@fastify/session';
import { sessionSecret } from './nestvexa.config${ext}';

interface PluginHost {
  register(plugin: unknown, options?: object): PromiseLike<unknown>;
}
function isPluginHost(value: unknown): value is PluginHost {
  return (
    typeof value === 'object' &&
    value !== null &&
    typeof Reflect.get(value, 'register') === 'function'
  );
}

/**
 * Generated by \`nestvexa init\` on Fastify: guest sessions (@fastify/session
 * with its in-memory store) for Live identity and CSRF tokens. Use a
 * persistent store and your authentication before production. Call before
 * configureNestvexa(app).
 */
export async function configureSession(app: INestApplication): Promise<void> {
  const fastify: unknown = app.getHttpAdapter().getInstance();
  if (!isPluginHost(fastify)) throw new Error('configureSession expects the Fastify platform');
  await fastify.register(fastifyCookie);
  await fastify.register(fastifySession, {
    secret: sessionSecret(),
    saveUninitialized: false,
    cookie: { httpOnly: true, sameSite: 'strict', secure: process.env['NODE_ENV'] === 'production' },
  });
}
`;
}

