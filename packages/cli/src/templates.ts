export function resourceFiles(
  kebab: string,
  pascal: string,
  camel: string,
  esm: boolean,
) {
  const ext = esm ? '.js' : '';
  return {
    service: `import { Injectable, NotFoundException } from '@nestjs/common';

export interface ${pascal} {
  readonly id: number;
  readonly name: string;
}

/**
 * In-memory repository generated by \`nestvexa make:resource\`. Replace with your
 * ORM/data access; no schema migration is generated.
 */
@Injectable()
export class ${pascal}Service {
  #items: ${pascal}[] = [];
  #next = 1;
  list(): readonly ${pascal}[] {
    return this.#items;
  }
  create(name: string): ${pascal} {
    const item = { id: this.#next++, name };
    this.#items = [...this.#items, item];
    return item;
  }
  remove(id: number): void {
    if (!this.#items.some((item) => item.id === id)) throw new NotFoundException();
    this.#items = this.#items.filter((item) => item.id !== id);
  }
}
`,
    component: `import { Inject } from '@nestjs/common';
import { Action, Computed, LiveComponent, State } from 'nestvexa';
import { ${pascal}Service } from './${kebab}.service${ext}';

@LiveComponent({ name: '${kebab}-table', view: 'components/${kebab}-table' })
export class ${pascal}TableComponent {
  constructor(@Inject(${pascal}Service) private readonly ${camel}: ${pascal}Service) {}
  @State({ writable: true, validate: (value) => typeof value === 'string' && value.length <= 80 })
  draft = '';
  @State() error = '';
  @Computed() get rows() {
    return this.${camel}.list().map((item) => ({ ...item }));
  }
  @Action() create(): void {
    const name = this.draft.trim();
    this.error = name.length < 2 ? 'Enter at least 2 characters.' : '';
    if (this.error) return;
    this.${camel}.create(name);
    this.draft = '';
  }
}
`,
    view: `<section aria-label="${pascal}">
  <form nv:submit="create">
    <label for="${kebab}-draft">Name</label>
    <input id="${kebab}-draft" nv:model="draft" value="{{draft}}" maxlength="80" />
    <button type="submit">Add</button>
    {{#if error}}<p role="alert">{{error}}</p>{{/if}}
  </form>
  <ul>
    {{#each rows}}<li data-nv-key="${kebab}-{{id}}">{{name}}</li>{{else}}<li>No items yet.</li>{{/each}}
  </ul>
</section>
`,
  };
}
export function resourceController(
  kebab: string,
  pascal: string,
  camel: string,
  esm: boolean,
): string {
  const ext = esm ? '.js' : '';
  return `import {
  BadRequestException,
  Body,
  Controller,
  Delete,
  Get,
  HttpCode,
  Inject,
  Param,
  ParseIntPipe,
  Post,
} from '@nestjs/common';
import { ${pascal}Service } from './${kebab}.service${ext}';
import type { ${pascal} } from './${kebab}.service${ext}';

/** REST routes generated by \`nestvexa make:resource --crud\`. Add guards before production. */
@Controller('${kebab}')
export class ${pascal}Controller {
  constructor(@Inject(${pascal}Service) private readonly ${camel}: ${pascal}Service) {}

  @Get()
  list(): readonly ${pascal}[] {
    return this.${camel}.list();
  }

  @Post()
  create(@Body() body: unknown): ${pascal} {
    const name: unknown =
      body && typeof body === 'object' ? Reflect.get(body, 'name') : undefined;
    if (typeof name !== 'string' || name.trim().length < 2 || name.length > 80)
      throw new BadRequestException('name must be 2 to 80 characters');
    return this.${camel}.create(name.trim());
  }

  @Delete(':id')
  @HttpCode(204)
  remove(@Param('id', ParseIntPipe) id: number): void {
    this.${camel}.remove(id);
  }
}
`;
}
