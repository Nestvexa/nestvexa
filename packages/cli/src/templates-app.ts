export function actionGroup(kebab: string, pascal: string): string {
  return `import { Injectable } from '@nestjs/common';
import { ActionContext, ActionGroup, ActionInput, ServerAction } from '@nestvexa/actions';

export interface ${pascal}GreetInput {
  readonly name: string;
}
export interface ${pascal}GreetResult {
  readonly message: string;
}
function isGreetInput(value: unknown): value is ${pascal}GreetInput {
  if (typeof value !== 'object' || value === null) return false;
  const name: unknown = Reflect.get(value, 'name');
  return typeof name === 'string' && name.trim().length > 0 && name.length <= 100;
}

/**
 * Generated by \`nestvexa make:action\`. Exposed at
 * POST /_nestvexa/actions/${kebab}/greet only because the class is listed in
 * actionGroups and the host policy allows it. Add Nest guards as usual.
 */
@Injectable()
@ActionGroup('${kebab}')
export class ${pascal}Actions {
  @ServerAction({ id: 'greet' })
  greet(
    @ActionInput() input: unknown,
    @ActionContext() context: ActionContext,
  ): ${pascal}GreetResult {
    if (!isGreetInput(input)) throw new TypeError('Expected { name: string }');
    // Identity comes from the host policy, never from the body.
    return { message: \`Hello \${input.name.trim()} (\${context.identity.subject})\` };
  }
}
`;
}
