/** express-session exposes `request.sessionID`, @fastify/session `request.session.sessionId`. */
function sessionId(platform: Platform): string {
  return platform === 'fastify'
    ? `const store = session(request);
  const id: unknown = store ? Reflect.get(store, 'sessionId') : undefined;`
    : "const id: unknown = Reflect.get(request, 'sessionID');";
}

/**
 * `nestvexa make:tenancy`: server-side tenant resolution through the kernel
 * request context (`resolvePrincipal`/`resolveTenant`, consumed by Live with
 * `kernelIdentity: true`), a tenant-scoped Live component, a page that selects
 * the tenant with a CSRF-checked form, and an isolation test.
 */
export function tenancyContext(platform: Platform): string {
  return `import { Injectable, Module } from '@nestjs/common';
import type { RequestContextOptions, RequestPrincipal } from 'nestvexa';

/*
 * Generated by \`nestvexa make:tenancy\`. The tenant of a request comes only from
 * the server-side session and is re-checked against the membership rule on every
 * request. Headers, query strings, bodies and Live state are never read, so a
 * browser cannot point a request at another tenant. The kernel attaches this
 * principal and tenant to every Live identity and binds component snapshots to
 * them (\`kernelIdentity: true\`), so a snapshot minted in one tenant is refused
 * after the session switches tenant.
 */

export interface Tenant {
  readonly slug: string;
  readonly name: string;
}
/** Sample tenants. Replace with your tenant table. */
export const tenants: readonly Tenant[] = [
  { slug: 'acme', name: 'Acme' },
  { slug: 'globex', name: 'Globex' },
];
const tenantKey = 'nestvexaTenant';

function session(request: object): object | undefined {
  const value: unknown = Reflect.get(request, 'session');
  return value && typeof value === 'object' ? value : undefined;
}

/**
 * Who may enter which tenant. This guest starter lets every session join any
 * sample tenant; replace it with your membership check (for example a
 * \`memberships\` table keyed by user and tenant) before production.
 */
export function isMember(principal: RequestPrincipal, tenant: string): boolean {
  void principal;
  return tenants.some((candidate) => candidate.slug === tenant);
}

/** The guest session is the principal. Replace with your authenticated user. */
export function resolvePrincipal(request: object): RequestPrincipal | undefined {
  ${sessionId(platform)}
  return typeof id === 'string' && id ? { id: \`guest:\${id}\` } : undefined;
}

/** The session's selected tenant, only while the principal is still a member. */
export function resolveTenant(request: object): string | undefined {
  const principal = resolvePrincipal(request);
  const store = session(request);
  const selected: unknown = store ? Reflect.get(store, tenantKey) : undefined;
  return principal && typeof selected === 'string' && isMember(principal, selected)
    ? selected
    : undefined;
}

/** Store the selected tenant in the session after the membership check. */
export function selectTenant(request: object, slug: string): boolean {
  const principal = resolvePrincipal(request);
  const store = session(request);
  if (!principal || !store || !isMember(principal, slug)) return false;
  Reflect.set(store, tenantKey, slug);
  return true;
}

/** Kernel request context: pass as \`requestContext\` of the kernel registration. */
export const tenancyRequestContext: RequestContextOptions = {
  resolvePrincipal,
  resolveTenant,
};

/**
 * Tenant-scoped notes in process memory. Every method takes the tenant from
 * the caller, which resolves it on the server; a real store filters every
 * query by a tenant column the same way.
 */
@Injectable()
export class TenantNotesStore {
  readonly #notes = new Map<string, string[]>();
  list(tenant: string): string[] {
    return [...(this.#notes.get(tenant) ?? [])];
  }
  add(tenant: string, note: string): void {
    const notes = this.#notes.get(tenant) ?? [];
    notes.push(note);
    this.#notes.set(tenant, notes.slice(-50));
  }
}

/** Provides the store to the tenant-scoped Live components (liveImports). */
@Module({ providers: [TenantNotesStore], exports: [TenantNotesStore] })
export class TenancyModule {}
`;
}

export function tenantNotesComponent(esm: boolean): string {
  const ext = esm ? '.js' : '';
  return `import { ForbiddenException, Inject } from '@nestjs/common';
import { REQUEST } from '@nestjs/core';
import { Action, LiveComponent, RequestContextFactory, State } from 'nestvexa';
import { TenantNotesStore } from './tenancy${ext}';

const noteField = (value: unknown) =>
  typeof value === 'string' && value.length <= 200;

/**
 * Generated by \`nestvexa make:tenancy\`: a Live component whose data is scoped
 * to the request's kernel tenant. The tenant is resolved again on every mount
 * and action; the \`tenant\` state is display-only and never writable.
 */
@LiveComponent({ name: 'tenant-notes', view: 'components/tenant-notes' })
export class TenantNotesComponent {
  constructor(
    @Inject(REQUEST) private readonly request: object,
    @Inject(RequestContextFactory) private readonly context: RequestContextFactory,
    @Inject(TenantNotesStore) private readonly store: TenantNotesStore,
  ) {}
  @State() tenant = '';
  @State() notes: string[] = [];
  @State({ writable: true, validate: noteField }) draft = '';
  @State() error = '';

  async mount(): Promise<void> {
    this.tenant = await this.currentTenant();
    this.notes = this.store.list(this.tenant);
  }
  @Action() async add(): Promise<void> {
    const tenant = await this.currentTenant();
    const note = this.draft.trim();
    if (!note) {
      this.error = 'Write a note first.';
      return;
    }
    this.store.add(tenant, note);
    this.tenant = tenant;
    this.notes = this.store.list(tenant);
    this.draft = '';
    this.error = '';
  }
  /** The kernel tenant of this request; no tenant selected means no access. */
  private async currentTenant(): Promise<string> {
    const { tenant } = await this.context.identity(this.request);
    if (!tenant) throw new ForbiddenException('Select a tenant first');
    return tenant;
  }
}
`;
}

export function tenantNotesView(): string {
  return `<section aria-label="Tenant notes">
  <h2>Notes for {{tenant}}</h2>
  <ul id="tenant-notes">
    {{#each notes}}<li>{{this}}</li>{{else}}<li>No notes in this tenant yet.</li>{{/each}}
  </ul>
  <form nv:submit="add">
    <label for="tenant-note">New note</label>
    <input id="tenant-note" nv:model="draft" value="{{draft}}" maxlength="200" />
    <button type="submit" nv:loading.attr="disabled" nv:target="add">Add note</button>
  </form>
  <p role="status">{{error}}</p>
</section>
`;
}

export function tenancyController(esm: boolean): string {
  const ext = esm ? '.js' : '';
  return `import {
  BadRequestException,
  Body,
  Controller,
  ForbiddenException,
  Get,
  Header,
  Headers,
  Inject,
  Post,
  Redirect,
  Render,
  Req,
} from '@nestjs/common';
import { randomBytes, timingSafeEqual } from 'node:crypto';
import { LiveRuntime, RequestContextFactory } from 'nestvexa';
import { TenantNotesComponent } from './tenant-notes.component${ext}';
import { selectTenant, tenants } from './tenancy${ext}';

interface SessionRequest {
  session: Record<string, unknown>;
}
function sameSecret(expected: unknown, actual: unknown): boolean {
  if (typeof expected !== 'string' || typeof actual !== 'string') return false;
  const left = Buffer.from(expected);
  const right = Buffer.from(actual);
  return left.length === right.length && timingSafeEqual(left, right);
}

/** Generated by \`nestvexa make:tenancy\`: choose a tenant, then work inside it. */
@Controller('tenancy')
export class TenancyController {
  constructor(
    @Inject(LiveRuntime) private readonly live: LiveRuntime,
    @Inject(RequestContextFactory) private readonly context: RequestContextFactory,
  ) {}

  @Get()
  @Header('Cache-Control', 'no-store')
  @Render('tenancy')
  async index(@Req() request: SessionRequest) {
    request.session['csrf'] ??= randomBytes(32).toString('base64url');
    const { tenant } = await this.context.identity(request);
    return {
      title: tenant ? \`Tenant \${tenant}\` : 'Choose a tenant',
      csrf: request.session['csrf'],
      tenant: tenant ?? '',
      tenants: tenants.map((entry) => ({ ...entry, current: entry.slug === tenant })),
      notes: tenant ? await this.live.mount(TenantNotesComponent, request) : '',
    };
  }

  /** A plain form POST: same origin, the session CSRF token, then the membership check. */
  @Post('select')
  @Redirect('/tenancy', 303)
  select(
    @Req() request: SessionRequest,
    @Body() body: unknown,
    @Headers('origin') origin: string | undefined,
  ): void {
    const expected = process.env['NESTVEXA_ORIGIN'] ?? 'http://localhost:3000';
    if (origin !== undefined && origin !== expected) throw new ForbiddenException();
    const field = (name: string): unknown =>
      body && typeof body === 'object' ? Reflect.get(body, name) : undefined;
    if (!sameSecret(request.session['csrf'], field('_csrf'))) throw new ForbiddenException();
    const slug = field('tenant');
    if (typeof slug !== 'string' || !selectTenant(request, slug))
      throw new BadRequestException('Unknown tenant');
  }
}
`;
}

export function tenancyPage(): string {
  return `<h1>{{title}}</h1>
<form method="post" action="/tenancy/select">
  <input type="hidden" name="_csrf" value="{{csrf}}" />
  <fieldset>
    <legend>Tenant</legend>
    {{#each tenants}}
    <label>
      <input type="radio" name="tenant" value="{{slug}}" {{#if current}}checked{{/if}} />
      {{name}}
    </label>
    {{/each}}
  </fieldset>
  <button type="submit">Open tenant</button>
</form>
{{#if tenant}}{{notes}}{{else}}<p>Choose a tenant to see its notes.</p>{{/if}}
`;
}

function testImports(runner: TestRunner): string {
  return runner === 'vitest'
    ? "import { describe, expect, it } from 'vitest';"
    : "import { describe, expect, it } from '@jest/globals';";
}
export function tenancyTest(
  runner: TestRunner,
  platform: Platform,
  esm: boolean,
): string {
  const ext = esm ? '.js' : '';
  const request = (id: string, extra: string) =>
    platform === 'fastify'
      ? `{ session: { sessionId: '${id}'${extra} }`
      : `{ sessionID: '${id}', session: {${extra ? extra.slice(1) : ''} }`;
  return `import 'reflect-metadata';
${testImports(runner)}
import {
  TenantNotesStore,
  resolvePrincipal,
  resolveTenant,
  selectTenant,
} from './tenancy${ext}';

/** Generated by \`nestvexa make:tenancy\`: tenant resolution and data isolation. */
describe('tenancy', () => {
  it('resolves the tenant only from the server-side session', () => {
    const alice = ${request('alice', '')}, headers: { 'x-tenant': 'globex' }, query: { tenant: 'globex' } };
    expect(resolveTenant(alice)).toBeUndefined();
    expect(selectTenant(alice, 'acme')).toBe(true);
    expect(resolvePrincipal(alice)).toEqual({ id: 'guest:alice' });
    // A forged header or query string never changes the tenant.
    expect(resolveTenant(alice)).toBe('acme');
  });

  it('refuses unknown tenants and requests without a session', () => {
    const bob = ${request('bob', '')} };
    expect(selectTenant(bob, 'initech')).toBe(false);
    expect(resolveTenant(bob)).toBeUndefined();
    expect(resolveTenant({})).toBeUndefined();
    expect(selectTenant({}, 'acme')).toBe(false);
    // A tenant written into the session by other code must still pass the membership rule.
    const forged = ${request('eve', ", nestvexaTenant: 'initech'")} };
    expect(resolveTenant(forged)).toBeUndefined();
  });

  it('keeps each tenant\\'s data separate', () => {
    const store = new TenantNotesStore();
    store.add('acme', 'Acme only');
    expect(store.list('acme')).toEqual(['Acme only']);
    expect(store.list('globex')).toEqual([]);
    store.list('acme').push('mutated copy');
    expect(store.list('acme')).toEqual(['Acme only']);
  });
});
`;
}
