import { createReadStream } from 'node:fs';
import { copyFile, mkdir, rename, rm, stat, unlink } from 'node:fs/promises';
import {
  dirname,
  isAbsolute,
  normalize,
  relative,
  resolve,
  sep,
} from 'node:path';
import type { Readable } from 'node:stream';
import { fail } from './errors.js';

/** Inclusive byte range. */
export interface ByteRange {
  readonly start: number;
  readonly end: number;
}
/** A fully validated temporary file being committed to permanent storage. */
export interface StorageSource {
  readonly path: string;
  readonly size: number;
  /** Lower-case hex SHA-256 of the exact bytes. */
  readonly sha256: string;
  readonly contentType: string;
}
export interface StoredObject {
  readonly key: string;
  readonly size: number;
}
/** Presigned request for a browser to send bytes directly to object storage. */
export interface DirectUploadTarget {
  readonly url: string;
  readonly method: 'PUT';
  /** Headers the browser must send exactly; they are part of the signature. */
  readonly headers: Readonly<Record<string, string>>;
  readonly expiresAt: number;
}
export interface PresignedDownloadOptions {
  readonly filename: string;
  readonly contentType: string;
  readonly expiresInSeconds?: number;
  readonly disposition?: 'attachment' | 'inline';
}

/**
 * Permanent storage for finalized uploads. Keys are always generated by the
 * upload service (`[A-Za-z0-9_-]` shard/name); adapters must still reject any
 * other key shape, and never accept URLs or paths from requests.
 */
export interface UploadStorage {
  readonly kind: string;
  put(key: string, source: StorageSource): Promise<StoredObject>;
  open(key: string, range?: ByteRange): Promise<Readable>;
  stat(key: string): Promise<{ readonly size: number } | undefined>;
  delete(key: string): Promise<void>;
  /** Optional direct-to-storage support (S3-compatible presigned PUT). */
  presignUpload?(
    key: string,
    options: {
      readonly contentType: string;
      readonly size: number;
      readonly expiresInSeconds: number;
    },
  ): Promise<DirectUploadTarget>;
  /** Optional presigned GET for downloads served by the storage provider. */
  presignDownload?(
    key: string,
    options: PresignedDownloadOptions,
  ): Promise<string>;
}

const keyPattern = /^[A-Za-z0-9_-]{2}\/[A-Za-z0-9_-]{43}$/;
/** Throws unless the key has the exact generated shape. */
export function assertStorageKey(key: unknown): asserts key is string {
  if (typeof key !== 'string' || !keyPattern.test(key))
    throw new Error('Invalid storage key');
}

export interface LocalStorageOptions {
  /** Absolute directory outside any static/webroot directory. */
  readonly directory: string;
}

/** Local filesystem storage (default). Files are written with owner-only permissions. */
export class LocalStorage implements UploadStorage {
  readonly kind = 'local';
  readonly directory: string;
  constructor(options: LocalStorageOptions) {
    if (
      !options ||
      typeof options.directory !== 'string' ||
      !isAbsolute(options.directory) ||
      options.directory.includes('\u0000')
    )
      throw new Error('LocalStorage requires an absolute directory');
    this.directory = resolve(normalize(options.directory));
  }
  /** Canonical path inside the storage root; throws for any escaping key. */
  path(key: string): string {
    assertStorageKey(key);
    const target = resolve(this.directory, ...key.split('/'));
    const rel = relative(this.directory, target);
    if (
      !rel ||
      rel.startsWith('..') ||
      isAbsolute(rel) ||
      rel.split(sep).includes('..')
    )
      throw new Error('Storage key escapes its root');
    return target;
  }
  async put(key: string, source: StorageSource): Promise<StoredObject> {
    const target = this.path(key);
    await mkdir(dirname(target), { recursive: true, mode: 0o700 });
    try {
      await rename(source.path, target);
    } catch (error) {
      // Different volumes: copy, then remove the temporary file.
      if ((error as NodeJS.ErrnoException).code !== 'EXDEV') throw error;
      await copyFile(source.path, target);
      await unlink(source.path).catch(() => undefined);
    }
    const info = await stat(target);
    if (info.size !== source.size) {
      await rm(target, { force: true });
      fail(500, 'STORAGE_FAILED');
    }
    return Object.freeze({ key, size: info.size });
  }
  async open(key: string, range?: ByteRange): Promise<Readable> {
    const target = this.path(key);
    await stat(target).catch(() => fail(404, 'UPLOAD_NOT_FOUND'));
    return createReadStream(
      target,
      range === undefined ? {} : { start: range.start, end: range.end },
    );
  }
  async stat(key: string): Promise<{ readonly size: number } | undefined> {
    try {
      const info = await stat(this.path(key));
      return info.isFile() ? Object.freeze({ size: info.size }) : undefined;
    } catch {
      return undefined;
    }
  }
  async delete(key: string): Promise<void> {
    await rm(this.path(key), { force: true });
  }
}
