import { existsSync, readdirSync, readFileSync, realpathSync } from 'node:fs';
import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import ts from 'typescript';

// Public API reports (QA-040, QA-049, QA-090). For every published package and
// every `exports` entry with typings, this lists each exported declaration as
// it appears in the built `.d.ts` (comments removed), plus the package-local
// declarations those exports reference without exporting them, so a change to
// a "forgotten" options interface still shows up. Reports are committed under
// `api-reports/`; `pnpm api:check` fails when the built typings no longer match
// them, and `pnpm api:update` rewrites them. See docs/contributing/api-reports.md.
// The output is deterministic: names are sorted, paths are package-relative
// and line endings are LF on every OS.

const reportDirectory = 'api-reports';
const banner = [
  '> Generated by `pnpm api:update` (scripts/api-report.mjs) from the built `.d.ts`',
  '> files. Do not edit by hand. A change here is a public API change: review it',
  '> and add a changeset (docs/contributing/api-reports.md).',
];

const toPosix = (path) => path.replace(/\\/g, '/');

/**
 * Published workspace packages and their typed entry points.
 * @param {string} root
 */
export function listPackages(root) {
  const packagesDir = join(root, 'packages');
  if (!existsSync(packagesDir)) return [];
  const result = [];
  for (const entry of readdirSync(packagesDir, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const dir = join(packagesDir, entry.name);
    const manifestFile = join(dir, 'package.json');
    if (!existsSync(manifestFile)) continue;
    const manifest = JSON.parse(readFileSync(manifestFile, 'utf8'));
    if (manifest.private === true || typeof manifest.name !== 'string')
      continue;
    const entries = [];
    const exportsField =
      typeof manifest.exports === 'string' || manifest.exports === undefined
        ? { '.': manifest.exports ?? manifest.types ?? manifest.main }
        : manifest.exports;
    for (const [subpath, target] of Object.entries(exportsField)) {
      const types = typesFor(target);
      if (types === undefined) continue;
      entries.push({
        subpath,
        specifier:
          subpath === '.'
            ? manifest.name
            : `${manifest.name}${subpath.slice(1)}`,
        types,
        file: resolve(dir, types),
      });
    }
    entries.sort((a, b) => a.specifier.localeCompare(b.specifier, 'en'));
    result.push({ dir: entry.name, path: dir, name: manifest.name, entries });
  }
  return result.sort((a, b) => a.dir.localeCompare(b.dir, 'en'));
}

/** The `.d.ts` file an export condition object resolves to, if any. */
function typesFor(target) {
  if (typeof target === 'string') {
    if (target.endsWith('.d.ts')) return target;
    if (target.endsWith('.js')) return target.replace(/\.js$/, '.d.ts');
    return undefined;
  }
  if (target === null || typeof target !== 'object') return undefined;
  if (typeof target.types === 'string') return target.types;
  for (const key of ['import', 'default', 'node'])
    if (key in target) {
      const nested = typesFor(target[key]);
      if (nested !== undefined) return nested;
    }
  return undefined;
}

/**
 * Builds every report in memory.
 * @param {string} root Repository root containing `packages/`.
 * @returns {Map<string, string>} report file name -> contents
 */
export function generateReports(root) {
  const packages = listPackages(root);
  const files = packages.flatMap((pkg) =>
    pkg.entries
      .filter((entry) => existsSync(entry.file))
      .map((entry) => entry.file),
  );
  const program = ts.createProgram(files, {
    module: ts.ModuleKind.NodeNext,
    moduleResolution: ts.ModuleResolutionKind.NodeNext,
    target: ts.ScriptTarget.ES2022,
    noEmit: true,
    skipLibCheck: true,
    // Declarations are printed, not type-checked: the standard library and
    // ambient @types packages are not needed and only slow the program down.
    noLib: true,
    types: [],
  });
  const checker = program.getTypeChecker();
  const printer = ts.createPrinter({
    removeComments: true,
    newLine: ts.NewLineKind.LineFeed,
  });
  const packageRoots = packages.map((pkg) => ({
    name: pkg.name,
    root: toPosix(safeRealpath(pkg.path)) + '/',
  }));

  /** The workspace package (or external module) that owns a declaration file. */
  const ownerOf = (fileName) => {
    const path = toPosix(safeRealpath(fileName));
    const owner = packageRoots.find((candidate) =>
      path.startsWith(candidate.root),
    );
    if (owner)
      return {
        name: owner.name,
        workspace: true,
        file: path.slice(owner.root.length),
      };
    const match = /\/node_modules\/((?:@[^/]+\/)?[^/]+)\//.exec(path);
    return { name: match?.[1] ?? 'external', workspace: false, file: '' };
  };

  const resolveAlias = (symbol) =>
    symbol.flags & ts.SymbolFlags.Alias
      ? checker.getAliasedSymbol(symbol)
      : symbol;

  const declarationsOf = (symbol) =>
    [...(symbol.declarations ?? [])].sort((a, b) => {
      const fa = toPosix(a.getSourceFile().fileName);
      const fb = toPosix(b.getSourceFile().fileName);
      return fa === fb ? a.pos - b.pos : fa.localeCompare(fb, 'en');
    });

  const render = (declaration) => {
    const sourceFile = declaration.getSourceFile();
    if (ts.isVariableDeclaration(declaration)) {
      const flags = declaration.parent.flags;
      const keyword =
        flags & ts.NodeFlags.Const
          ? 'const'
          : flags & ts.NodeFlags.Let
            ? 'let'
            : 'var';
      return `declare ${keyword} ${printer.printNode(ts.EmitHint.Unspecified, declaration, sourceFile)};`;
    }
    if (ts.isSourceFile(declaration)) return '/* module namespace */';
    return printer
      .printNode(ts.EmitHint.Unspecified, declaration, sourceFile)
      .replace(/^export (default )?/, '');
  };

  /** Package-local symbols referenced from a declaration's type positions. */
  const referencedSymbols = (declaration) => {
    const found = [];
    const visit = (node) => {
      let name;
      if (ts.isTypeReferenceNode(node)) name = node.typeName;
      else if (ts.isExpressionWithTypeArguments(node)) name = node.expression;
      else if (ts.isTypeQueryNode(node)) name = node.exprName;
      if (name) {
        const symbol = checker.getSymbolAtLocation(
          ts.isQualifiedName(name) ? name.right : name,
        );
        if (symbol) found.push(resolveAlias(symbol));
      }
      ts.forEachChild(node, visit);
    };
    visit(declaration);
    return found;
  };

  const reports = new Map();
  for (const pkg of packages) {
    const exported = new Set();
    const sections = [];
    const seeds = [];
    for (const entry of pkg.entries) {
      const sourceFile = program.getSourceFile(entry.file);
      const lines = [];
      if (!sourceFile) {
        sections.push({
          entry,
          lines: ['// Typings not built: run `pnpm build` first.'],
        });
        continue;
      }
      const moduleSymbol = checker.getSymbolAtLocation(sourceFile);
      const exports = moduleSymbol
        ? [...checker.getExportsOfModule(moduleSymbol)].sort((a, b) =>
            a.name.localeCompare(b.name, 'en'),
          )
        : [];
      for (const symbol of exports) {
        const target = resolveAlias(symbol);
        exported.add(target);
        const declarations = declarationsOf(target);
        const owners = new Set(
          declarations.map((declaration) =>
            ownerOf(declaration.getSourceFile().fileName),
          ),
        );
        const foreign = [...owners].find((owner) => owner.name !== pkg.name);
        if (declarations.length === 0) {
          lines.push(`// ${symbol.name}: unresolved export`);
          continue;
        }
        if (foreign) {
          const alias = target.name === symbol.name ? '' : ` as ${symbol.name}`;
          lines.push(
            `export { ${target.name}${alias} } from '${foreign.name}';${foreign.workspace ? ' // see its report' : ''}`,
          );
          continue;
        }
        const renamed =
          target.name === symbol.name || target.name === 'default'
            ? ''
            : ` (local name ${target.name})`;
        lines.push(`// ${symbol.name}${renamed}`);
        for (const declaration of declarations) {
          lines.push(render(declaration));
          seeds.push(declaration);
        }
        lines.push('');
      }
      sections.push({ entry, lines });
    }

    // Unexported package-local declarations reachable from the public surface.
    const forgotten = new Map();
    const queue = [...seeds];
    while (queue.length > 0) {
      const declaration = queue.shift();
      for (const symbol of referencedSymbols(declaration)) {
        if (exported.has(symbol) || forgotten.has(symbol)) continue;
        const declarations = declarationsOf(symbol).filter((candidate) => {
          if (candidate.kind === ts.SyntaxKind.TypeParameter) return false;
          const owner = ownerOf(candidate.getSourceFile().fileName);
          return owner.workspace && owner.name === pkg.name;
        });
        if (declarations.length === 0) continue;
        forgotten.set(symbol, declarations);
        queue.push(...declarations);
      }
    }

    const out = [`# API report: \`${pkg.name}\``, '', ...banner, ''];
    for (const { entry, lines } of sections) {
      out.push(
        `## \`${entry.specifier}\``,
        '',
        `Typings: \`${entry.types}\``,
        '',
        '```ts',
      );
      while (lines.at(-1) === '') lines.pop();
      out.push(...(lines.length ? lines : ['// no exports']), '```', '');
    }
    if (forgotten.size > 0) {
      out.push(
        '## Referenced but not exported',
        '',
        'Public signatures use these declarations; changing them changes the public API.',
        '',
        '```ts',
      );
      const entries = [...forgotten.entries()]
        .map(([symbol, declarations]) => ({
          symbol,
          declarations,
          file: ownerOf(declarations[0].getSourceFile().fileName).file,
        }))
        .sort((a, b) =>
          a.symbol.name === b.symbol.name
            ? a.file.localeCompare(b.file, 'en')
            : a.symbol.name.localeCompare(b.symbol.name, 'en'),
        );
      for (const { symbol, declarations, file } of entries) {
        out.push(`// ${symbol.name} (${file})`);
        for (const declaration of declarations) out.push(render(declaration));
        out.push('');
      }
      while (out.at(-1) === '') out.pop();
      out.push('```', '');
    }
    reports.set(`${pkg.dir}.api.md`, out.join('\n'));
  }
  return reports;
}

function safeRealpath(path) {
  try {
    return realpathSync(path);
  } catch {
    return path;
  }
}

/**
 * Compares generated reports with the committed ones.
 * @param {Map<string, string>} reports
 * @param {string} directory
 */
export async function compareReports(reports, directory) {
  const existing = existsSync(directory)
    ? (await readdir(directory)).filter((file) => file.endsWith('.api.md'))
    : [];
  const changed = [];
  for (const [file, contents] of reports) {
    const path = join(directory, file);
    const current = existsSync(path)
      ? (await readFile(path, 'utf8')).replace(/\r\n/g, '\n')
      : undefined;
    if (current !== contents) changed.push({ file, current, next: contents });
  }
  const stale = existing.filter((file) => !reports.has(file));
  return { changed, stale };
}

/** A short line diff for the console: the first differing lines of each file. */
export function describeChange({ file, current, next }, limit = 40) {
  if (current === undefined) return `${file}: new report (not committed yet)`;
  const before = current.split('\n');
  const after = next.split('\n');
  const removed = before.filter((line) => !after.includes(line));
  const added = after.filter((line) => !before.includes(line));
  const lines = [
    ...removed.map((line) => `- ${line}`),
    ...added.map((line) => `+ ${line}`),
  ];
  const shown = lines.slice(0, limit);
  if (lines.length > limit)
    shown.push(`  ... ${lines.length - limit} more changed lines`);
  return [`${file}:`, ...shown.map((line) => `  ${line}`)].join('\n');
}

async function main() {
  const root = process.cwd();
  const mode = process.argv.includes('--update') ? 'update' : 'check';
  const directory = join(root, reportDirectory);
  const reports = generateReports(root);
  const unbuilt = [...reports.entries()].filter(([, text]) =>
    text.includes('Typings not built'),
  );
  if (unbuilt.length > 0) {
    console.error(
      `Missing built typings for ${unbuilt.map(([file]) => file).join(', ')}; run \`pnpm build\` first.`,
    );
    process.exitCode = 1;
    return;
  }
  const { changed, stale } = await compareReports(reports, directory);
  if (mode === 'update') {
    await mkdir(directory, { recursive: true });
    for (const { file, next } of changed) {
      await mkdir(dirname(join(directory, file)), { recursive: true });
      await writeFile(join(directory, file), next);
    }
    for (const file of stale) await rm(join(directory, file));
    console.log(
      `API reports: ${changed.length} updated, ${stale.length} removed, ${reports.size - changed.length} unchanged.`,
    );
    return;
  }
  if (changed.length === 0 && stale.length === 0) {
    console.log(
      `API reports match the built typings (${reports.size} packages).`,
    );
    return;
  }
  for (const change of changed) console.error(describeChange(change));
  for (const file of stale)
    console.error(`${file}: report for a package that is no longer published`);
  console.error(
    '\nThe public API differs from api-reports/. If the change is intended, run `pnpm build && pnpm api:update`,\n' +
      'commit the reports and add a changeset with the matching bump (docs/contributing/api-reports.md).',
  );
  process.exitCode = 1;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) await main();
