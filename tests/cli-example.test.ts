import { existsSync, readFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import { describe, expect, it } from 'vitest';
import { run } from '../packages/cli/dist/index.js';
import { json, node, repo } from './support/cli-fixture.js';

const example = join(repo, 'examples', 'cli-generated');
const regenerated = join(repo, 'artifacts', 'cli-example', 'regenerated');
/** Installed dependencies, builds and runtime data are not part of the example. */
const ignored = new Set(['node_modules', 'dist', 'storage', 'test-results']);

function files(root: string, directory = root): string[] {
  return readdirSync(directory).flatMap((entry) => {
    if (ignored.has(entry)) return [];
    const path = join(directory, entry);
    return statSync(path).isDirectory()
      ? files(root, path)
      : [relative(root, path).replaceAll('\\', '/')];
  });
}
// Git may check text files out with CRLF on Windows.
const text = (path: string) =>
  readFileSync(path, 'utf8').replaceAll('\r\n', '\n');

/**
 * examples/cli-generated is the committed output of
 * scripts/generate-cli-example.mjs. Regenerating it must reproduce every file
 * byte for byte, so the reference app always shows what the CLI emits today.
 */
describe('CLI-generated reference app', { timeout: 300_000 }, () => {
  it('matches a fresh regeneration by the CLI', () => {
    const result = node(
      [join(repo, 'scripts', 'generate-cli-example.mjs'), regenerated],
      repo,
    );
    expect(result.status, result.output).toBe(0);
    const expected = files(example).sort();
    const actual = files(regenerated).sort();
    expect(actual).toEqual(expected);
    for (const file of expected)
      expect(text(join(regenerated, file)), file).toBe(
        text(join(example, file)),
      );
    expect(expected).toEqual(
      expect.arrayContaining([
        '.nestvexa/manifest.json',
        'client/react/ssr.tsx',
        'client/vue/ssr.ts',
        'client/svelte/ssr.ts',
        'src/nestvexa/forms/contact.form.ts',
        'src/actions/greeter.actions.ts',
        'client/islands/clicker.tsx',
        'src/task/task.controller.ts',
        'src/nestvexa/realtime.config.ts',
        'src/nestvexa/uploads.config.ts',
        'src/nestvexa/i18n.config.ts',
      ]),
    );
  });

  it('passes the doctor and lists its routes once installed', () => {
    // `pnpm install` links the workspace packages into the example.
    expect(existsSync(join(example, 'node_modules', 'nestvexa'))).toBe(true);
    const saved = { ...process.env };
    try {
      delete process.env['NODE_ENV'];
      const doctor = run(['doctor', '--json'], example);
      const report = json(doctor);
      expect(report.ok, doctor.stdout.join('\n')).toBe(true);
      const status = Object.fromEntries(
        (report.data as { name: string; status: string }[]).map((check) => [
          check.name,
          check.status,
        ]),
      );
      expect(status).toMatchObject({
        nestvexa: 'pass',
        peers: 'pass',
        versions: 'pass',
        engines: 'pass',
        configure: 'pass',
        session: 'pass',
        csrf: 'pass',
        layout: 'pass',
      });
    } finally {
      process.env = saved;
    }
    const routes = json(run(['inspect:routes', '--json'], example));
    expect(JSON.stringify(routes.data)).toContain('/showcase');
    const migrate = run(['migrate', '--dry-run', '--json'], example);
    // Generated by the current CLI: no migration is pending.
    expect(json(migrate).ok).toBe(true);
    expect(json(migrate).changes ?? []).toEqual([]);
  });
});
