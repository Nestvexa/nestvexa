import { spawn } from 'node:child_process';
import { existsSync, renameSync } from 'node:fs';
import { join } from 'node:path';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { run } from '../packages/cli/dist/index.js';
import { boot, freshApp, node, ok, read, tsc } from './support/cli-fixture.js';
import type { BootedApp } from './support/cli-fixture.js';

// Assigned port for this suite: 3483.
const port = 3483;
const frameworks = ['react', 'vue', 'svelte'] as const;
const secret = 'cli-inertia-ssr-session-secret-0123456789abcdef';

/**
 * The Inertia roots generated by `nestvexa add react|vue|svelte` build with
 * Vite (client and SSR bundles) and render on the server in production.
 */
describe(
  'generated Inertia roots: Vite client and SSR builds',
  { timeout: 300_000 },
  () => {
    let root = '';
    let app: BootedApp | undefined;
    beforeAll(() => {
      root = freshApp('ssr-app', { directory: 'cli-inertia-ssr' });
      ok(run(['init'], root));
      for (const framework of frameworks) ok(run(['add', framework], root));
    }, 300_000);
    afterAll(() => {
      app?.stop();
    });

    it('builds every root with Vite into separate client and SSR outputs', () => {
      const vite = join(root, 'node_modules', 'vite', 'bin', 'vite.js');
      for (const framework of frameworks) {
        // The generated build script: client build, then the SSR bundle.
        const script = (
          JSON.parse(read(root, 'package.json')) as {
            scripts: Record<string, string>;
          }
        ).scripts[`build:${framework}`];
        const [client, server] = (script ?? '').split(' && ');
        for (const command of [client, server]) {
          const args = (command ?? '').split(' ').slice(1);
          expect(args[0]).toBe('build');
          // As `npm run build:<framework>` would: vitest itself runs with NODE_ENV=test.
          const result = node([vite, ...args], root, {
            ...process.env,
            NODE_ENV: 'production',
          });
          expect(result.status, `${framework}: ${result.output}`).toBe(0);
        }
        expect(
          existsSync(
            join(root, 'dist', framework, 'client', '.vite', 'manifest.json'),
          ),
        ).toBe(true);
        expect(
          existsSync(join(root, 'dist', framework, 'ssr', 'ssr.mjs')),
        ).toBe(true);
      }
      const server = tsc(root);
      expect(server.status, server.output).toBe(0);
    }, 900_000);

    it('server-renders each root in production and serves its hashed assets', async () => {
      app = await boot(root, port, {
        NODE_ENV: 'production',
        SESSION_SECRET: secret,
      });
      for (const [framework, title] of [
        ['react', 'Welcome · React'],
        ['vue', 'Welcome · Vue'],
        ['svelte', 'Welcome'],
      ] as const) {
        const response = await fetch(`${app.origin}/${framework}`);
        const html = await response.text();
        expect(response.status, html).toBe(200);
        expect(app.logs()).not.toContain('SSR failed');
        // The page body is rendered on the server, inside the Inertia root.
        expect(html).toMatch(/<h1[^>]*>Welcome<\/h1>/);
        expect(html).toContain(
          `Rendered by ${framework === 'react' ? 'React' : framework === 'vue' ? 'Vue' : 'Svelte'} through Inertia.`,
        );
        expect(html).toContain(`<title`);
        expect(html).toContain(title);
        expect(html).not.toContain('localhost:517');
        const script = new RegExp(
          `<script[^>]+src="(/build/${framework}/assets/[^"]+\\.js)"`,
        ).exec(html)?.[1];
        expect(script, html).toBeDefined();
        const asset = await fetch(`${app.origin}${script ?? ''}`);
        expect(asset.status).toBe(200);
        expect(asset.headers.get('content-type')).toContain('javascript');
        await asset.arrayBuffer();
      }
      app.stop();
      app = undefined;
    }, 600_000);

    it('refuses to start in production when an SSR bundle is missing', async () => {
      const bundle = join(root, 'dist', 'vue', 'ssr', 'ssr.mjs');
      renameSync(bundle, `${bundle}.bak`);
      try {
        const child = spawn(process.execPath, ['dist/src/main.js'], {
          cwd: root,
          env: {
            ...process.env,
            NODE_ENV: 'production',
            PORT: String(port),
            SESSION_SECRET: secret,
            NESTVEXA_ORIGIN: `http://127.0.0.1:${port}`,
          },
        });
        let logs = '';
        child.stderr.on('data', (chunk: Buffer) => (logs += chunk.toString()));
        const code = await new Promise<number | null>((done) =>
          child.on('exit', done),
        );
        expect(code).not.toBe(0);
        expect(logs).toContain('ssr.mjs is missing; run the vue build');
      } finally {
        renameSync(`${bundle}.bak`, bundle);
      }
    }, 300_000);
  },
);
